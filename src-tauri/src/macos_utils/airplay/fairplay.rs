//! The `/fp-setup` exchange.
//!
//! This is the only part of the AirPlay handshake that looks like crypto and
//! isn't. A receiver answers the two `POST /fp-setup` messages from a static
//! table: message 1 (16 bytes) selects one of four canned 142-byte replies by
//! `req[14]`, and message 2 (164 bytes) is answered with a fixed 12-byte header
//! followed by an echo of `req[144..164]`. No key material, no session state, no
//! randomness. The real FairPlay work only begins at `fairplay_decrypt`, which
//! recovers the AES key for the video stream — and we never decode video, so we
//! never go there.
//!
//! Reply tables and header transcribed from `lib/fairplay_playfair.c` of UxPlay
//! (Copyright (C) 2018 Juho Vähä-Herttua, LGPL-2.1-or-later), used here under
//! LGPL-2.1's "or later" grant via GPL-3, which AGPL-3 section 13 permits
//! combining with. Changed: transcribed to Rust, request dispatch keyed on the
//! message type/sequence bytes instead of on body length, and the table index
//! is bounds-checked.

