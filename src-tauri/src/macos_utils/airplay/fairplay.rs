const FP_HEADER: [u8; 12] = [
    0x46, 0x50, 0x4c, 0x59, 0x03, 0x01, 0x04, 0x00, 0x00, 0x00, 0x00, 0x14,
];

/// Offsets named by the reference receivers.
const VERSION_POS: usize = 4;
const TYPE_POS: usize = 5;
const SEQ_POS: usize = 6;
const MODE_POS: usize = 14;

const SETUP1_LEN: usize = 16;
const SETUP2_LEN: usize = 164;
const SETUP1_SEQ: u8 = 0x01;
const SETUP2_SEQ: u8 = 0x03;

/// Trailing 20 bytes of message 2 that get echoed back.
const ECHO_OFFSET: usize = 144;
const ECHO_LEN: usize = 20;

#[derive(Debug, PartialEq, Eq)]
pub enum FpError {
    /// FairPlay major version we have no table for. Only version 3 is known;
    /// a captured version-2 message exists in the wild with no published reply.
    UnsupportedVersion(u8),
    /// Length matched nothing we recognise.
    Unrecognized { len: usize, seq: u8 },
    /// `req[14]` indexed past the four known replies.
    BadMode(u8),
}

impl std::fmt::Display for FpError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            FpError::UnsupportedVersion(v) => write!(
                f,
                "fp-setup: FairPlay version {v} is not supported (only version 3 has published reply tables)"
            ),
            FpError::Unrecognized { len, seq } => {
                write!(f, "fp-setup: unrecognized message (len {len}, seq {seq})")
            }
            FpError::BadMode(m) => write!(f, "fp-setup: mode {m} is out of range 0..4"),
        }
    }
}

/// Answers one `POST /fp-setup` body.
pub fn respond(req: &[u8]) -> Result<Vec<u8>, FpError> {
    if req.len() <= MODE_POS {
        return Err(FpError::Unrecognized {
            len: req.len(),
            seq: 0,
        });
    }
    if req[VERSION_POS] != 0x03 {
        return Err(FpError::UnsupportedVersion(req[VERSION_POS]));
    }

    let seq = req[SEQ_POS];
    match (req.len(), seq) {
        (SETUP1_LEN, SETUP1_SEQ) | (SETUP1_LEN, _) => {
            let mode = req[MODE_POS];
            let table = REPLY_MESSAGES
                .get(mode as usize)
                .ok_or(FpError::BadMode(mode))?;
            Ok(table.to_vec())
        }
        (SETUP2_LEN, SETUP2_SEQ) | (SETUP2_LEN, _) => {
            let mut out = Vec::with_capacity(FP_HEADER.len() + ECHO_LEN);
            out.extend_from_slice(&FP_HEADER);
            out.extend_from_slice(&req[ECHO_OFFSET..ECHO_OFFSET + ECHO_LEN]);
            Ok(out)
        }
        (len, seq) => Err(FpError::Unrecognized { len, seq }),
    }
}

/// Message type byte, logged on first contact so an unexpected sender variant
/// is diagnosable rather than a silent no-connect.
pub fn describe(req: &[u8]) -> String {
    if req.len() <= MODE_POS {
        return format!("{} bytes (too short to classify)", req.len());
    }
    format!(
        "{} bytes, version {}, type {}, seq {}, mode {}",
        req.len(),
        req[VERSION_POS],
        req[TYPE_POS],
        req[SEQ_POS],
        req[MODE_POS],
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    fn setup1(mode: u8) -> Vec<u8> {
        let mut m = vec![0x46, 0x50, 0x4c, 0x59, 0x03, 0x01, 0x01, 0x00];
        m.extend_from_slice(&[0x00, 0x00, 0x00, 0x04, 0x02, 0x00, mode, 0x00]);
        m
    }

    #[test]
    fn message_one_selects_by_mode() {
        for mode in 0u8..4 {
            let r = respond(&setup1(mode)).expect("reply");
            assert_eq!(r.len(), 142);
            assert_eq!(&r[0..4], b"FPLY");
            assert_eq!(r[13], mode, "mode is echoed at index 13");
        }
    }

    #[test]
    fn replies_are_distinct_per_mode() {
        let a = respond(&setup1(0)).unwrap();
        let b = respond(&setup1(2)).unwrap();
        assert_ne!(a, b, "a single canned blob would be wrong for 3 of 4 modes");
    }

    #[test]
    fn out_of_range_mode_is_rejected_not_read_out_of_bounds() {
        assert_eq!(respond(&setup1(9)), Err(FpError::BadMode(9)));
    }

    #[test]
    fn message_two_echoes_its_tail() {
        let mut m = vec![0u8; SETUP2_LEN];
        m[0..4].copy_from_slice(b"FPLY");
        m[VERSION_POS] = 0x03;
        m[SEQ_POS] = SETUP2_SEQ;
        for i in 0..ECHO_LEN {
            m[ECHO_OFFSET + i] = 0xa0 + i as u8;
        }
        let r = respond(&m).expect("reply");
        assert_eq!(r.len(), 32);
        assert_eq!(&r[..12], &FP_HEADER);
        assert_eq!(&r[12..], &m[ECHO_OFFSET..ECHO_OFFSET + ECHO_LEN]);
    }

    #[test]
    fn version_two_is_reported_rather_than_answered_wrongly() {
        let m = vec![
            0x46, 0x50, 0x4c, 0x59, 0x02, 0x01, 0x01, 0x00, 0x00, 0x00, 0x00, 0x04, 0x02, 0x00,
            0x02, 0xbb,
        ];
        assert_eq!(respond(&m), Err(FpError::UnsupportedVersion(2)));
    }

    #[test]
    fn header_length_byte_matches_the_payload() {
        // index 11 is the body length after the 12-byte header
        assert_eq!(FP_HEADER[11] as usize, 32 - FP_HEADER.len());
        assert_eq!(REPLY_MESSAGES[0][11] as usize, 142 - 12);
    }
}
